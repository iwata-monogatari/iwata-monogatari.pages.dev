        markers = [
            r'<section\b[^>]*class="[^"]*\b(?:sources|references)\b',
            r'<p\b[^>]*class="section-label"[^>]*>\s*<strong>(?:主な)?参考資料',
            r'<section\b[^>]*class="[^"]*\brevision-history\b',
            r'<section\b[^>]*class="[^"]*\blocal-property-note\b',
            r'</article>', r'</main>',
        ]
        match = next((re.search(pattern, raw, flags=re.I) for pattern in markers if re.search(pattern, raw, flags=re.I)), None)
        if not match:
            raise RuntimeError(f"insertion marker missing: {filename}")
        raw = raw[:match.start()] + block.strip() + "\n" + raw[match.start():]
        if 'name="iwata:updated"' in raw:
            raw = re.sub(r'(<meta name="iwata:updated" content=")[^"]+', rf'\g<1>{DATE}', raw, count=1)
        else:
            raw = raw.replace('</head>', f'<meta name="iwata:updated" content="{DATE}">\n</head>', 1)
