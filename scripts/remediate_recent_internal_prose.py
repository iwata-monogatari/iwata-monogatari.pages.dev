def replace_section(raw: str, old_heading: str, new_heading: str, body: str) -> str:
    if f"<h2>{new_heading}</h2>" in raw:
        return raw
    pattern = re.compile(
        rf"<h2>{re.escape(old_heading)}</h2>.*?(?=<p class=\"note\"|<section class=\"refs\")",
        re.S,
    )
    replacement = f"<h2>{new_heading}</h2>{body}"
    raw, count = pattern.subn(replacement, raw, count=1)
    if count != 1:
        raise RuntimeError(f"section not found: {old_heading}")
    return raw


def main() -> None:
    changed = set()
    for filename, replacements in EXACT_REPLACEMENTS.items():
        path = ROOT / filename
        if not path.exists():
            continue
        raw = path.read_text(encoding="utf-8")
        original = raw
        for old, new in replacements.items():
            if old not in raw:
                continue
            raw = raw.replace(old, new)
        if raw != original:
            path.write_text(raw, encoding="utf-8")
            changed.add(filename)
    for filename, (old_heading, new_heading, body) in SECTION_REPLACEMENTS.items():
        path = ROOT / filename
        raw = path.read_text(encoding="utf-8")
        revised = replace_section(raw, old_heading, new_heading, body)
        path.write_text(revised, encoding="utf-8")
        changed.add(filename)
    print(f"remediated {len(changed)} recent pages")


if __name__ == "__main__":
    main()
