def insert(path: Path, addition: str) -> None:
    raw = path.read_text(encoding="utf-8-sig")
    if START in raw:
        before, rest = raw.split(START, 1)
        _, after = rest.split(END, 1)
        raw = before + addition.strip("\n") + after
    else:
        marker = "</article>" if "</article>" in raw else "</main>"
        pos = raw.rfind(marker)
        if pos < 0:
            raise RuntimeError(f"insertion marker missing: {path.name}")
        raw = raw[:pos] + addition + raw[pos:]
    path.write_text(raw, encoding="utf-8", newline="\n")


