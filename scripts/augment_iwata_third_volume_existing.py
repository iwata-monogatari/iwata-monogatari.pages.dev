def inject(path: Path, block: str) -> None:
    block = block.replace("<h2>", '<p class="section-label"><strong>').replace("</h2>", "</strong></p>")
    raw = path.read_text(encoding="utf-8")
    if START in raw:
        before, rest = raw.split(START, 1)
        _, after = rest.split(END, 1)
        raw = before + START + block + END + after
    else:
        marker = "</article>" if "</article>" in raw else "</main>"
        if marker not in raw:
            raise RuntimeError(f"content close missing: {path.name}")
        raw = raw.replace(marker, f"{START}{block}{END}\n{marker}", 1)
    path.write_text(raw, encoding="utf-8", newline="\n")


def main() -> None:
    for filename, block in BLOCKS.items():
        inject(ROOT / filename, "\n" + block.strip() + "\n")
    print(f"enhanced {len(BLOCKS)} existing articles")


if __name__ == "__main__":
    main()
