/* ---------- 語尾・文法の変換 ----------
   日本語の活用を厳密に解析せず、語末パターンで近似する。
   できるだけ誤爆を避けるため、固有の語尾から順に適用。     */

function endingsS2E(t, mode){
  // --- 理由：〜だから / 〜なので → だもんで ---
  t = t.replace(/だから/g, "だもんで");
  t = t.replace(/なので/g, "なもんで");
  t = t.replace(/ので/g, "もんで");
  // 動詞・形容詞の終止形＋から → もんで（来るから→来るもんで、寒いから→寒いもんで）
  // ただし「見つからない」等の語幹内「から」を誤爆しないよう、直後が否定・連用に続く場合は除外
  t = t.replace(/([るくぐすつぬむういた])から(?=[、。\s])/g, "$1もんで");
  t = t.replace(/([るくぐすつぬむういた])から(?![ないなかなくれっ])(?=[ぁ-んァ-ヶ一-龠])/g, "$1もんで");

  // --- 過去否定：〜なかった → んかった(ふつう) / なんだ(ガチ) ---
  // 「〜らなかった」「〜れなかった」等の動詞過去否定を対象
  if(mode==="gachi"){
    t = t.replace(/([かがさたなはまらやわいきしちにひみりえけせてねへめれ])なかった/g, "$1なんだ");
  }else{
    t = t.replace(/([かがさたなはまらやわいきしちにひみりえけせてねへめれ])なかった/g, "$1んかった");
  }

  // --- 現在否定：〜ない → 〜ん（動詞否定）---
  // 形容詞「〜ない（無い/赤くない等）」を避けるのは難しいので、
  // 直前が動詞未然形になりやすい音のときだけ変換する近似。
  t = t.replace(/([かがさたまらやわいきしちにみりえけせてねめれ])ない(?=$|[。、！？\s）」])/g, "$1ん");
  t = t.replace(/しない/g, "せん");
  t = t.replace(/来ない/g, "来ん");

  // --- 推量・確認：〜だろう/でしょう → だら/ら/ずら ---
  // 名詞・形容動詞のあとの「だろう/でしょう」→ だら(ふつう)/ずら(ガチ)
  const dara = (mode==="gachi") ? "ずら" : "だら";
  t = t.replace(/でしょうか/g, dara+"か");
  t = t.replace(/だろうか/g, dara+"か");
  t = t.replace(/でしょう/g, dara);
  t = t.replace(/だろう/g, dara);
  // 動詞・形容詞の終止形＋「だろ?」相当はここでは深追いしない

  // --- 慣用的な言い回し（勧誘規則より先に）---
  t = t.replace(/やめておこう/g, "いいにしよう");
  t = t.replace(/やめよう/g, "いいにしよう");
  t = t.replace(/やめておく/g, "いいにする");

  // --- 勧誘：〜しよう / 〜ようか → 〜まい(か) ---
  t = t.replace(/しようか/g, "しまいか");
  t = t.replace(/しよう/g, "しまい");
  t = t.replace(/やってみよう/g, "やってみまい");
  t = t.replace(/([きしちにみりいえけせてねめ])ようか/g, "$1まいか");
  t = t.replace(/([きしちにみりいえけせてねめ])よう(?=$|[。、！？\s）」])/g, "$1まい");

  // --- 断定・念押し：〜だよ → だに / 〜するよ → するに ---
  t = t.replace(/だよ/g, "だに");
  t = t.replace(/ますよ/g, "ますに");
  t = t.replace(/([るすくぐむぶぬう])よ(?=$|[。、！？\s）」])/g, "$1に");

  // --- 同意・確認：〜じゃない（か）→ じゃん(か) ---
  t = t.replace(/じゃないか/g, "じゃんか");
  t = t.replace(/ではないか/g, "じゃんか");
  t = t.replace(/じゃないですか/g, "じゃんね");

  // --- 疑問の緩和：〜か？ → 〜け？（体言・形容動詞のあと中心）---
  // 「ですか」→「け」、「するか」→「するけ」など軽めに
  t = t.replace(/ですか/g, "け");
  t = t.replace(/ます ?か/g, "ますか"); // 丁寧形は据え置き
  // 名詞＋か？ の単純疑問
  t = t.replace(/([ぁ-んァ-ヶ一-龠])か？/g, "$1け？");

  // --- やわらか命令：〜なさい → 〜ない / 〜てごらん → 〜てごう ---
  t = t.replace(/なさい/g, "ない");
  t = t.replace(/てごらん/g, "てごう");
  t = t.replace(/でごらん/g, "でごう");

  // --- 「〜です」を軽い言い切りに（ふつうは控えめ、ガチは「だに」寄り）---
  // 丁寧文はあえて崩しすぎない（読みやすさ優先）

  // --- 可能：ら抜き・れ足す（軽い範囲で）---
  t = t.replace(/食べられる/g, "食べれる");
  t = t.replace(/見られる/g, "見れる");
  t = t.replace(/来られる/g, "来れる");
  t = t.replace(/られる/g, "れる");

  // --- 磐田=中遠：おる/とる は使わない（いる/てる へ寄せる）---
  t = t.replace(/とる(?=$|[。、！？\s）」])/g, "てる");

  // --- 保護していた慣用句の復元 ---
  t = t.replace(/いいにしまい/g, "いいにしよう");

  return t;
}

/* ---------- 標準語→遠州弁 本体 ---------- */
function s2e(src, mode){
  let t = src;
  // 1) 語尾・文法を先に変換
  t = endingsS2E(t, mode);
  // 2) 語彙を置換（長い順／モードでガチ語彙を有効化）
  const list = VOCAB
    .filter(v => v[2]==="all" || mode==="gachi") // ふつうはall語彙のみ、ガチは全部
    .slice()
    .sort((a,b)=> b[0].length - a[0].length);
  for(const [a,b] of list){ t = t.split(a).join(b); }
  // 3) ガチの仕上げ：強調「とても」相当を「がんこ」に寄せる等は語彙で対応済み
  return t;
}

/* ---------- 遠州弁→標準語（簡易逆引き）---------- */
function e2s(src){
  let t = src;
  // 語尾を戻す
  t = t.replace(/だもんで/g,"だから");
  t = t.replace(/なもんで/g,"なので");
  t = t.replace(/もんで/g,"ので");
  t = t.replace(/(?<!いた)ずら(か)?(?=$|[。、！？!?\s）」]|(?:なあ|ね|な)(?=$|[。、！？!?\s）」]))/g, (_, q) => "だろう" + (q || ""));
  t = t.replace(/(?<!ま)(?<!だら)だら(か)?(?=$|[。、！？!?\s）」]|(?:なあ|ね|な)(?=$|[。、！？!?\s）」]))/g, (_, q) => "だろう" + (q || ""));
  t = t.replace(/だに/g,"だよ");
  t = t.replace(/([るすくぐむぶぬう])に(?=$|[。、！？!?\s）」])/g,"$1よ");
  t = t.replace(/じゃんか/g,"じゃないか");
  t = t.replace(/じゃんね/g,"じゃない");
  t = t.replace(/じゃん/g,"じゃない");
  t = t.replace(/(?<!お)しまい(か)?(?=$|[。、！？!?\s）」])/g, (_, q) => "しよう" + (q || ""));
  t = t.replace(/まいか/g,"ようか");
  t = t.replace(/てごう/g,"てごらん");
  // 否定・過去否定
  t = t.replace(/(?<=[かがさたはまらやわきしちにひみりけせてへめれ])なんだ(?=$|[。、！？\s）」])/g,"なかった");
  t = t.replace(/んかった/g,"なかった");
  t = t.replace(/せん(?=$|[。、！？\s）」])/g,"しない");
  // 語彙を戻す（長い順）
  const rev = VOCAB.map(v=>[v[1],v[0]]).sort((a,b)=>b[0].length-a[0].length);
  for(const [a,b] of rev){ t = t.split(a).join(b); }
  return t;
}


